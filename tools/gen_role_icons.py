"""Converts the composer's embedded role icons (webp/svg data URIs) to 64x64 PNGs and writes src/addon/role_icons.hpp.
usage: python3 tools/gen_role_icons.py /path/to/raid_squad_composer.html src/addon/role_icons.hpp"""
import base64, sys
from playwright.sync_api import sync_playwright
src, out = sys.argv[1], sys.argv[2]
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/opt/pw-browsers/chromium'); pg = b.new_page()
    pg.goto('file://' + src)
    icons = pg.evaluate("""async () => {
      const res = {};
      for (const [k, uri] of Object.entries(ICON_MAP)) {
        const img = new Image(); img.src = uri; await img.decode();
        const c = document.createElement('canvas'); c.width = c.height = 64;
        const x = c.getContext('2d'); x.clearRect(0, 0, 64, 64);
        const s = Math.min(64 / img.width, 64 / img.height, 64);
        const w = img.width * s, h = img.height * s;
        x.drawImage(img, (64 - w) / 2, (64 - h) / 2, w, h);
        res[k] = c.toDataURL('image/png').split(',')[1];
      }
      return res;
    }""")
lines = ['// GENERATED by tools/gen_role_icons.py from the composer\'s embedded icons - do not edit.', '#pragma once', '#include <cstddef>', '']
for k, v in sorted(icons.items()):
    raw = base64.b64decode(v)
    lines.append('static const unsigned char kRoleIcon_%s[] = {%s};' % (k, ','.join(str(x) for x in raw)))
lines.append('struct RoleIconData { const char* id; const unsigned char* data; size_t size; };')
lines.append('static const RoleIconData kRoleIcons[] = {')
for k in sorted(icons): lines.append('  {"%s", kRoleIcon_%s, sizeof kRoleIcon_%s},' % (k, k, k))
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print(len(icons), 'icons')
