// Generates src/core/unicode_tables.cpp from the JavaScript engine's own Unicode data, so the
// addon classifies letters/digits and lowercases names exactly like the composer's JavaScript does.
// Run: node tools/gen_unicode_tables.js > src/core/unicode_tables.cpp
const re = /[\p{L}\p{N}]/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x10FFFF; cp++) {
  const isSurrogate = cp >= 0xD800 && cp <= 0xDFFF;
  const hit = !isSurrogate && re.test(String.fromCodePoint(cp));
  if (hit && start < 0) start = cp;
  if (!hit && start >= 0) { ranges.push([start, cp - 1]); start = -1; }
}
if (start >= 0) ranges.push([start, 0x10FFFF]);

const lower = [];
for (let cp = 0; cp <= 0x10FFFF; cp++) {
  if (cp >= 0xD800 && cp <= 0xDFFF) continue;
  const s = String.fromCodePoint(cp);
  const l = s.toLowerCase();
  if (l === s) continue;
  const cps = Array.from(l).map(c => c.codePointAt(0));
  if (cps.length > 2) throw new Error('unexpected lowercase expansion for U+' + cp.toString(16));
  lower.push([cp, cps[0], cps[1] || 0]);
}
const hex = n => '0x' + n.toString(16).toUpperCase();
let out = '// GENERATED by tools/gen_unicode_tables.js (node ' + process.version + ', Unicode via V8) - do not edit.\n';
out += '#include "unicode_tables.hpp"\n\nnamespace sw { namespace uni {\n\n';
out += 'const Range kLetterNumber[] = {\n';
for (let i = 0; i < ranges.length; i += 6) out += '  ' + ranges.slice(i, i + 6).map(r => '{' + hex(r[0]) + ',' + hex(r[1]) + '}').join(', ') + ',\n';
out += '};\nconst size_t kLetterNumberCount = ' + ranges.length + ';\n\n';
out += 'const LowerMap kLower[] = {\n';
for (let i = 0; i < lower.length; i += 5) out += '  ' + lower.slice(i, i + 5).map(r => '{' + hex(r[0]) + ',' + hex(r[1]) + ',' + hex(r[2]) + '}').join(', ') + ',\n';
out += '};\nconst size_t kLowerCount = ' + lower.length + ';\n\n}} // namespace sw::uni\n';
process.stdout.write(out);
